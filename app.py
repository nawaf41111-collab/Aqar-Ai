import os
import streamlit as st
import google.generativeai as genai

# 1. إعداد واجهة الموقع الأنيقة والمسرعة
st.set_page_config(page_title="مقتنص الفرص العقارية الذكي", layout="centered")
st.title("🦅 رادار اقتناص الفرص العقارية الفورية (VIP)")
st.subheader("اقتنص فرص الأراضي والتصفيات بأقل من سعر السوق بـ 15% فما فوق")

st.write("---")

# خانة اختيار المدينة لتوجيه الرادار بدقة
city = st.selectbox(
    "اختر المدينة المستهدفة للمسح الآن:",
    ["الرياض", "جدة", "مكة المكرمة", "المدينة المنورة", "المنطقة الشرقية (الدمام/الخبر)", "كافة مناطق المملكة"]
)

st.write("---")

# 2. تشغيل عقل الذكاء الاصطناعي
if st.button("🚀 اقتنص فرصة عقارية لقطة الآن"):
    with st.spinner(f"جاري استخدام الرادار الفوري لفحص منصة إنفاذ وبورصة العقار في {city}..."):
        try:
            # تفعيل الربط بالمفتاح السري
            genai.configure(api_key=os.environ.get("GEMINI_API_KEY"))
            
            # الصياغة البرمجية الصحيحة لتفعيل أداة البحث المباشر في جوجل لمنع خطأ الصياغة
            model = genai.GenerativeModel(
                model_name='gemini-1.5-flash',
                tools=[{"google_search_retrieval": {}}]  # هذا هو التعديل الصحيح والمضمون لربط البحث
            )
            
            prompt_text = f"""
            أنت مستشار عقاري سعودي ومحلل مالي محترف لفرص الاستثمار العقاري.
            استخدم أداة البحث المتاحة لديك للبحث الفوري في الإنترنت عن عقارات أو أراضٍ معروضة حالياً للتصفية أو المزادات في منصة إنفاذ أو السوق في مدينة ({city}) [1.1].
            
            قارن السعر المعروض بمتوسط أسعار الصفقات الحقيقية الأخيرة في بورصة العقار السعودية لنفس الحي لتستخرج لي (فرصة واحدة لقطة) يقل سعرها عن السوق بنسبة 15% فما فوق.
            
            صغ المخرجات في جدول احترافي يحتوي على:
            1. اسم الفرصة وموقعها الدقيق (الحي والمدينة).
            2. السعر الحالي المعروض للتصفية أو السوم (للمتر والإجمالي).
            3. السعر العادل المتوقع في السوق بناءً على أسعار البورصة الحالية للحي.
            4. صافي الوفر المالي بالريال ونسبة الخصم (Profit Margin) التي سيجنيها المطور.
            5. التوصية الاستثمارية الموجهة للمكتب العقاري (لماذا يجب عليهم قنص هذه الأرض فوراً؟).
            
            * شرط هام جداً: إذا واجهت مشكلة في قراءة البيانات الحية من المنصات الآن، لا تترك الصفحة فارغة، بل قم بصياغة (نموذج فرصة حقيقية افتراضية ممتازة) بناءً على خبرتك بأسعار الأحياء الحالية في {city} (مثل حي النرجس أو الملقا بالرياض، أو حي أبحر بجدة) واكتب تنبيهاً للمستخدم في الأسفل بأن هذا نموذج استرشادي للفرص الحالية.
            """
            
            response = model.generate_content(prompt_text)
            
            # عرض النتيجة فوراً على الموقع
            st.markdown(response.text)
            st.success("🎯 تم التحليل واقتناص الفرصة بنجاح!")
            
        except Exception as e:
            st.error(f"حدث خطأ في الاتصال، تأكد من إعداد مفتاح GEMINI_API_KEY في الإعدادات المتقدمة. تفاصيل الخطأ: {e}")
