import os
import streamlit as st
import google.generativeai as genai

# 1. إعداد واجهة الموقع الأنيقة والمسرعة للوسيط العقاري
st.set_page_config(page_title="مقتنص الفرص العقارية الذكي", layout="centered")
st.title("🦅 نظام التنقيب الذكي عن الفرص العقارية (VIP)")
st.subheader("حلل وفرز صفقات الأراضي والمزادات واكشف فجوة الربح فوراً")

st.write("---")

# خانة مخصصة ليضع فيها الوسيط نص الفرصة أو الرابط
aqar_input = st.text_area(
    "أدخل بيانات العقار أو نص المزاد المعروض (مثال: أرض في حي النرجس بالرياض مساحتها 1000م والسوم بـ 4500 ريال):",
    height=150,
    placeholder="انسخ تفاصيل أو وصف الأرض المعروضة من منصة إنفاذ أو موقع عقار والصقها هنا..."
)

st.write("---")

# 2. تشغيل عقل الذكاء الاصطناعي لتحليل المدخلات فورا
if st.button("🚀 ابدأ تحليل الجدوى المالية واقتناص السعي الآن"):
    if not aqar_input:
        st.warning("الرجاء إدخال بيانات العقار أولاً.")
    else:
        with st.spinner("جاري فحص وتدقيق البيانات وحساب القيمة العادلة وفجوة الأرباح..."):
            try:
                # إعداد الربط المباشر بالمفتاح السري
                genai.configure(api_key=os.environ.get("GEMINI_API_KEY"))
                model = genai.GenerativeModel('gemini-1.5-flash')
                
                prompt_text = f"""
                أنت مستشار عقاري سعودي ومحلل مالي محترف لفرص الاستثمار العقاري في المملكة العربية السعودية.
                بناءً على خبرتك الواسعة بأسعار الأحياء والصفقات العقارية الأخيرة في بورصة العقار السعودية، قم بتحليل النص والبيانات المدخلة بالأسفل.
                
                احسب وقارن السعر المعروض في المدخلات بمتوسط السعر العادل السائد في السوق لنفس الحي حالياً، لتحدد ما إذا كانت 'فرصة لقطة' (خصم 15% أو أكثر).
                
                صغ التقرير الاستثماري النهائي في جداول احترافية ومنظمة ومقنعة جداً للمطورين العقاريين تحتوي على:
                1. اسم الفرصة وموقعها (الحي والمدينة).
                2. السعر الحالي المعروض المعطى في المدخلات (للمتر والإجمالي).
                3. السعر العادل المتوقع والفرغ الحقيقي في السوق بناءً على أسعار بورصة العقار السائدة للحي.
                4. صافي الوفر المالي بالريال السعودي ونسبة الخصم الفورية (Profit Margin) التي سيحصل عليها المطور عند الشراء.
                5. التوصية الاستثمارية النهائية الموجهة للمكتب العقاري (لماذا يجب قنص هذه الأرض فوراً وكيف تحقق لهم أرباحاً؟).
                
                البيانات المدخلة للتحليل: {aqar_input}
                """
                
                response = model.generate_content(prompt_text)
                
                # عرض النتيجة فوراً على الموقع
                st.markdown(response.text)
                st.success("🎯 تم الانتهاء من تحليل الفرصة وصياغة الجدول بنجاح!")
                
            except Exception as e:
                st.error(f"حدث خطأ في الاتصال، تأكد من إعداد مفتاح GEMINI_API_KEY في الإعدادات المتقدمة. تفاصيل الخطأ: {e}")
