import os
import streamlit as st
import google.generativeai as genai

# 1. إعداد واجهة الموقع الأنيقة والمسرعة للوسيط العقاري
st.set_page_config(page_title="مقتنص الفرص العقارية الذكي", layout="centered")
st.title("🦅 رادار اقتناص الفرص العقارية الفورية (VIP)")
st.subheader("اقتنص فرص الأراضي والتصفيات بأقل من سعر السوق بـ 15% فما فوق بضغطة زر")

st.write("---")

# خانة اختيار المدينة لتوجيه الرادار بدقة
city = st.selectbox(
    "اختر المدينة المستهدفة للمسح الآن:",
    ["الرياض", "جدة", "مكة المكرمة", "المدينة المنورة", "المنطقة الشرقية (الدمام/الخبر)", "كافة مناطق المملكة"]
)

st.write("---")

# 2. تشغيل عقل الذكاء الاصطناعي المسرّع بفرصة واحدة مركزة
if st.button("🚀 اقتنص فرصة عقارية لقطة الآن"):
    with st.spinner(f"جاري استخدام الرادار الفوري لفحص منصة إنفاذ وبورصة العقار في {city}..."):
        try:
            # إعداد الربط السليم والمجاني السريع
            genai.configure(api_key=os.environ.get("GEMINI_API_KEY"))
            model = genai.GenerativeModel('gemini-1.5-flash')
            
            # أمر برمجي خفيف ومحدد يضمن السرعة القصوى في جلب البيانات
            prompt_text = f"""
            أنت مستشار عقاري سعودي ومحلل مالي محترف لفرص الاستثمار العقاري.
            استخدم محرك البحث المتاح لديك لتصفح الإنترنت والبحث في المواقع الرسمية مثل منصة إنفاذ للمزادات وبورصة العقار السعودية لاستخراج بيانات حقيقية قريبة.
            
            ابحث واستخرج بدقة (فرصة عقارية واحدة فقط أو أرض واحدة معروضة للبيع أو التصفية حالياً) في مدينة ({city}).
            يجب أن تكون هذه الفرصة "لقطة"، أي أن سعر المتر المعروض فيها أقل من متوسط أسعار الصفقات الحقيقية في بورصة العقار لنفس الحي بنسبة 15% فما فوق.
            
            صغ المخرجات في جدول احترافي ومنظم يحتوي على:
            1. اسم الفرصة وموقعها الدقيق (الحي والمدينة).
            2. السعر الحالي المعروض للتصفية أو السوم الحالي (للمتر والإجمالي).
            3. السعر العادل المتوقع في السوق بناءً على أسعار بورصة العقار الحالية للحي.
            4. صافي الوفر المالي بالريال السعودي ونسبة الخصم (Profit Margin) التي سيجنيها المطور عند الشراء.
            5. التوصية الاستثمارية الموجهة للمكتب العقاري (لماذا يجب عليهم قنص هذه الأرض فوراً؟).
            
            ملاحظة هامة: ركز على جلب فرصة واحدة حقيقية ودقيقة بأسرع وقت ممكن واصنع جدولاً واحداً فائق الدقة والاكتمال.
            """
            
            response = model.generate_content(prompt_text)
            st.markdown(response.text)
            st.success("🎯 تم اقتناص الفرصة بنجاح! إذا كنت تريد فرصة أخرى، اضغط على الزر مجدداً.")
            
        except Exception as e:
            st.error(f"حدث خطأ في الاتصال، تأكد من إعداد مفتاح GEMINI_API_KEY في الإعدادات المتقدمة. تفاصيل الخطأ: {e}")
